import type { MediaSlot } from "@/content/media";
import { typo, typoDeep } from "@/lib/typography";

/**
 * Четыре свадьбы из папки weddings/.
 *
 * Что здесь достоверно: сами фотографии и даты — они взяты из имён файлов
 * и подтверждаются кадрами (у первой свадьбы дата напечатана в фотозоне,
 * у третьей — на экране в зале).
 *
 * Что нужно подтвердить у заказчика перед публикацией:
 * — названия проектов. У первой свадьбы «Отражение двух миров» снято
 *   с самой фотозоны, остальные три названы по визуальной теме и являются
 *   рабочими;
 * — имена пар. Не выдуманы и не подставлены: их просто нет. Публиковать
 *   имена и лица можно только с письменного согласия пар;
 * — площадки и число гостей — стоит «уточняется».
 */

/** Один кадр в галерее. span: 2 — снимок на всю ширину сетки. */
export type GalleryItem = MediaSlot & { span?: 1 | 2 };

export type Work = {
  id: string;
  /** Название проекта. Имён пар в данных намеренно нет. */
  title: string;
  /** Дата словами — она же подпись под названием. */
  date: string;
  /** Кадр в сетке портфолио. */
  cover: MediaSlot;
  /** Крупный кадр в шапке развёрнутой карточки. */
  hero: MediaSlot;
  /** Одна фраза, задающая настроение свадьбы. */
  lead: string;
  facts: { label: string; value: string }[];
  story: string[];
  gallery: GalleryItem[];
};

/** Собирает путь images/works/<slug>/<file>, чтобы не повторять его руками. */
function shot(
  slug: string,
  file: string,
  label: string,
  ratio: string,
  span?: 1 | 2,
  position?: string,
): GalleryItem {
  return {
    src: "/images/works/" + slug + "/" + file,
    file: "images/works/" + slug + "/" + file,
    label,
    ratio,
    span,
    position,
  };
}

