import { typo } from "@/lib/typography";

/**
 * Русская типографика для текста прямо в разметке.
 *
 * JSX склеивает многострочный текст в одну строку ещё при сборке, поэтому
 * сюда приходит готовый абзац. В исходнике текст остаётся обычным — без
 * &nbsp; и невидимых неразрывных пробелов, которые не заметишь при правке.
 */
export function Typo({ children }: { children: string }) {
  return typo(children);
}
