/**
 * Русская типографика: расстановка неразрывных пробелов.
 *
 * Правила, которые здесь закрыты:
 * — короткие предлоги, союзы и частицы не остаются висеть в конце строки;
 * — тире не переносится на новую строку в одиночестве;
 * — не разрываются разряды чисел, число с валютой и число со следующим словом;
 * — не отрывается № от номера.
 *
 * Применяется к данным из src/content (через typoDeep), поэтому новый текст
 * получает правильные переносы автоматически — достаточно писать обычными
 * пробелами. В разметке компонентов для тех же целей стоят сущности &nbsp;.
 */

const NBSP = "\u00A0";

/**
 * Слова, после которых перенос запрещён: все одно- и двухбуквенные плюс
 * трёхбуквенные предлоги и союзы.
 */
const HANGING =
  /(^|[\s(«„—])((?:[а-яё]{1,2}|для|или|над|под|при|без|про|как|что))[ ]/gi;

export function typo(text: string): string {
  let out = text;

  // Короткие слова могут идти подряд («и в которых»), поэтому проходим
  // до тех пор, пока замены ещё случаются.
  let previous: string;
  do {
    previous = out;
    out = out.replace(HANGING, `$1$2${NBSP}`);
  } while (out !== previous);

  return (
    out
      // тире держится за предыдущим словом
      .replace(/ —/g, `${NBSP}—`)
      // разряды чисел: 120 000
      .replace(/(\d)[ ](?=\d)/g, `$1${NBSP}`)
      // число не отрывается от валюты, процента и следующего слова
      .replace(/(\d)[ ](?=[₽%А-Яа-яЁё])/g, `$1${NBSP}`)
      // № не отрывается от номера
      .replace(/№[ ]/g, `№${NBSP}`)
  );
}

/** Есть ли в строке кириллица — типографику применяем только к русскому тексту. */
const isRussian = (value: string) => /[А-Яа-яЁё]/.test(value);

/**
 * Рекурсивно применяет типографику ко всем русским строкам внутри данных.
 * Пути к файлам, идентификаторы, ссылки и пропорции остаются нетронутыми:
 * в них нет кириллицы.
 */
export function typoDeep<T>(value: T): T {
  if (typeof value === "string") {
    return (isRussian(value) ? typo(value) : value) as T;
  }

  if (Array.isArray(value)) {
    return value.map(typoDeep) as T;
  }

  if (value !== null && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value).map(([key, item]) => [key, typoDeep(item)]),
    ) as T;
  }

  return value;
}
